"""Generate src/proxy_multi.cpp + src/proxy.def: ONE dll that works as winmm.dll, version.dll, dinput8.dll,
xinput1_3.dll or dsound.dll (2026-11-14: some systems will not load a given proxy name, as with Ghost AI's version.dll;
shared with the T7 Jukebox). Every call forwards to System32\\<this file's own name> (proxy_common.hpp).

- Named exports of all five DLLs (union; shared names like DllGetClassObject once): forward BY NAME, at ordinals
  from 1000 up so they never collide.
- Ordinals 1..max of all five: generic stubs, "ordinal N" forwards to ordinal N of the real DLL. The game imports
  dsound (#8 #11 #12) and xinput1_3 (#2 #3 #4) BY ORDINAL, so these must keep their numbers whatever the name is.
- Not exported: DllMain (xinput1_3 exports one by name).
All exports of these DLLs take at most 8 integer/pointer arguments (no floats): one generic x64 forwarder fits.
Run on a dev PC (reads C:/Windows/System32)."""
import pefile

DLLS = ["winmm", "version", "dinput8", "xinput1_3", "dsound"]
COM_PRIVATE = {"DllCanUnloadNow", "DllGetClassObject", "DllRegisterServer", "DllUnregisterServer"}

names, max_ord = {}, 0
for dll in DLLS:
    pe = pefile.PE(rf"C:/Windows/System32/{dll}.dll", fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    for s in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        max_ord = max(max_ord, s.ordinal)
        if s.name and s.name.decode() != "DllMain":
            names.setdefault(s.name.decode(), dll)

cpp = ["// GENERATED by tools/gen_proxy.py - one proxy for winmm / version / dinput8 / xinput1_3 / dsound.",
       "// Named exports forward by name, ordinals 1..%d forward to the same ordinal of the real DLL." % max_ord,
       '#include "proxy_common.hpp"', ""]
de = ["LIBRARY winmm", "EXPORTS"]
for o in range(1, max_ord + 1):
    cpp.append(f"T7_FORWARD_ORD({o})")
    de.append(f"\tord{o}=proxy_ord{o} @{o} NONAME")
for i, n in enumerate(sorted(names)):
    cpp.append(f"T7_FORWARD({n})")
    # COM entry points: PRIVATE and without an ordinal (LNK4222); COM finds them by name
    de.append(f"\t{n}=proxy_{n} PRIVATE" if n in COM_PRIVATE else f"\t{n}=proxy_{n} @{1000 + i}")
open("src/proxy_multi.cpp", "w", newline="\r\n").write("\n".join(cpp) + "\n")
open("src/proxy.def", "w", newline="\r\n").write("\n".join(de) + "\n")
print(f"{len(names)} named exports, ordinals 1..{max_ord}")
